// Usage: node scripts/generate-seed.mjs > supabase/seed.sql
// Builds a demo seed from src/data/mockData.js. Everything is marked as sample data.
// Deliberately NOT seeded: photos (stock images), video clips (stock videos), NISN, previous-test values (no real date).
import { playersRoster } from '../src/data/mockData.js';

const q = (v) => (v === null || v === undefined ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);
const num = (v) => (v === null || v === undefined || Number.isNaN(Number(v)) ? 'NULL' : Number(v));
const attr = (p, key) => {
  const a = (p.radar_attributes || []).find((x) => x.attribute.toLowerCase().includes(key));
  return a ? Number(a.value) : 'NULL';
};

const out = [];
out.push('-- GENERATED by scripts/generate-seed.mjs from src/data/mockData.js. DATA CONTOH (fiktif), bukan data anak sungguhan.');
out.push('-- Semua pemain dibuat PRIVATE. Tidak ada foto/video stok, NISN, atau nilai tes sebelumnya.');
out.push('BEGIN;');
const academy = playersRoster[0].personal_info.academy;
out.push(`INSERT INTO public.academies (id, name, city) VALUES ('aaaaaaaa-0000-4000-8000-000000000001', ${q(academy.name + ' (DATA CONTOH)')}, ${q(academy.city)}) ON CONFLICT (id) DO NOTHING;`);

for (const p of playersRoster) {
  const i = p.personal_info;
  out.push(`INSERT INTO public.players (public_id, academy_id, full_name, nickname, jersey_number, position, age_group, birth_date, height_cm, weight_kg, preferred_foot, visibility_tier)
VALUES (${q(p.player_id)}, 'aaaaaaaa-0000-4000-8000-000000000001', ${q(i.full_name)}, ${q(i.nickname)}, ${num(i.jersey_number)}, ${q(i.position)}, 'U-13', ${q(i.birth_date)}, ${num(i.height_cm)}, ${num(i.weight_kg)}, ${q(i.preferred_foot)}, 'private')
ON CONFLICT (public_id) DO NOTHING;`);

  const e = p.ai_coach_evaluation || {};
  out.push(`INSERT INTO public.player_assessments (player_id, period_month, coach_name, pace, shooting, passing, dribbling, defending, physical, ai_narrative, strengths, growth_areas, recommended_drill, is_published)
SELECT id, ${q(e.period || 'Oktober 2026')}, ${q(e.coach_name || 'Tim Pelatih')}, ${attr(p, 'pace')}, ${attr(p, 'shooting')}, ${attr(p, 'passing')}, ${attr(p, 'dribbling')}, ${attr(p, 'defending')}, ${attr(p, 'physical')}, ${q(e.narrative || '')}, ${q(JSON.stringify(e.strengths || []))}::jsonb, ${q(JSON.stringify(e.growth_areas || []))}::jsonb, ${q(JSON.stringify(e.recommended_drill || {}))}::jsonb, true
FROM public.players WHERE public_id = ${q(p.player_id)}
ON CONFLICT DO NOTHING;`);

  const f = p.fitness_benchmarks;
  if (f && f.test_date) {
    out.push(`INSERT INTO public.fitness_records (player_id, test_date, vertical_jump_cm, sprint_20m_sec, shuttle_run_sec, yoyo_score)
SELECT id, ${q(f.test_date)}, ${num(f.vertical_jump_cm)}, ${num(f.sprint_20m_sec)}, ${num(f.shuttle_run_sec)}, ${q(f.yoyo_level)}
FROM public.players WHERE public_id = ${q(p.player_id)}
AND NOT EXISTS (SELECT 1 FROM public.fitness_records r JOIN public.players pl ON pl.id = r.player_id WHERE pl.public_id = ${q(p.player_id)} AND r.test_date = ${q(f.test_date)});`);
  }
}
out.push('COMMIT;');
console.log(out.join('\n'));
